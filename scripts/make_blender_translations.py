"""Write tools/blender/io_scene_pt_ase/translations.py from the language tables (the bl.* texts of
src/PTSmd/lang/<code>.txt).  Blender shows them when its interface language is one of these
(Edit > Preferences > Interface > Translation).

    python make_blender_translations.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LANG = os.path.join(HERE, '..', 'src', 'PTSmd', 'lang')
OUT = os.path.join(HERE, '..', 'tools', 'blender', 'io_scene_pt_ase', 'translations.py')
# table -> Blender locale
LOCALES = {'ko': 'ko_KR', 'zh-CN': 'zh_HANS', 'zh-TW': 'zh_HANT', 'ja': 'ja_JP', 'th': 'th_TH',
           'vi': 'vi_VN', 'pt-BR': 'pt_BR', 'es': 'es'}


def load(code):
    d = {}
    for line in open(os.path.join(LANG, code + '.txt'), encoding='utf-8'):
        line = line.rstrip('\n')
        if line.startswith('bl.') and ' = ' in line:
            k, v = line.split(' = ', 1)
            d[k.strip()] = v.replace('\\n', '\n')
    return d


def fmt(s):
    return re.findall(r'%[-0-9.]*[dsf%]', s)


en = load('en')
out = ['# Generated by scripts/make_blender_translations.py from src/PTSmd/lang/*.txt - do not edit.',
       '# The add-on\'s interface in the languages of the game\'s source (Blender: Preferences > Interface > Translation).',
       'import bpy', '', 'TRANSLATIONS = {']
for code, loc in LOCALES.items():
    t = load(code)
    out.append('    %r: {' % loc)
    for k, e in en.items():
        if k not in t or t[k] == e:
            continue
        if fmt(t[k]) != fmt(e):
            raise SystemExit('%s %s: %% values differ from English' % (code, k))
        for ctx in ('*', 'Operator'):           # (operator names use the "Operator" context)
            out.append('        (%r, %r): %r,' % (ctx, e, t[k]))
    out.append('    },')
out += ['}', '', '',
        'def register():',
        '    try:',
        '        bpy.app.translations.register(__package__, TRANSLATIONS)',
        '    except ValueError:              # (already registered)',
        '        pass',
        '', '',
        'def unregister():',
        '    try:',
        '        bpy.app.translations.unregister(__package__)',
        '    except Exception:',
        '        pass', '']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('wrote', OUT, '(%d texts x %d languages)' % (len(en), len(LOCALES)))
